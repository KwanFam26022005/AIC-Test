"""## 1. Nhanh Tag Detection -- RAM++

Dong goi lai logic suy luan RAM++ thanh mot ham `get_ram_tags()` de co the tai su dung
cho moi keyframe trong pipeline, thay vi viet code roi rac nhu notebook goc.

"""

import torch
from PIL import Image
from ram.models import ram_plus
from ram import inference_ram as inference
from ram import get_transform

# ---- Thiet lap thiet bi & nap mo hinh RAM++ (chi load mot lan) ----
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f"Dang chay tren thiet bi: {device}")

RAM_IMAGE_SIZE = 384
RAM_CHECKPOINT = "pretrained/ram_plus_swin_large_14m.pth"

print("Dang nap mo hinh RAM++ (Swin-Large)...")
ram_model = ram_plus(pretrained=RAM_CHECKPOINT, image_size=RAM_IMAGE_SIZE, vit='swin_l')
ram_model.eval()
ram_model = ram_model.to(device)
ram_transform = get_transform(image_size=RAM_IMAGE_SIZE)
print("RAM++ da san sang.")


def get_ram_tags(image: Image.Image):
    """Chay RAM++ tren mot anh PIL, tra ve danh sach tag tieng Anh da lam sach.

    Tuong ung module 'Tag Detection (RAM)' trong Fig. 2 cua paper -> output la
    'List tags of objects in frame'.
    """
    image_tensor = ram_transform(image.convert("RGB")).unsqueeze(0).to(device)
    with torch.no_grad():
        res = inference(image_tensor, ram_model)

    raw_tags = res[0]  # vi du: "dog | grass | playing"
    tag_list = [t.strip() for t in raw_tags.split("|") if t.strip()]
    return tag_list


# ---- Test nhanh ----
