"""## 2. Nhanh Object Detection -- Grounding DINO

Day la phan **bo sung chinh** theo yeu cau: dung chinh cac tag vua lay duoc tu RAM++ lam
**text prompt** cho Grounding DINO de thuc hien *zero-shot object detection*, tu do suy ra
bounding box cho tung tag -- dung nhu mo ta o muc 4.4 cua paper:

> *"...to forecast bounding boxes for image tags... a feature improvement component,
> linguistic question selection, and a multimodal decoder that improves linguistic
> integration over standard detectors."*

"""

from transformers import AutoProcessor, AutoModelForZeroShotObjectDetection

# Co 2 lua chon checkpoint:
#   - "IDEA-Research/grounding-dino-tiny"  -> nhe, toc do nhanh, phu hop demo / Colab T4
#   - "IDEA-Research/grounding-dino-base"  -> chinh xac cao hon, dung khi trien khai thuc
GROUNDING_DINO_MODEL_ID = "IDEA-Research/grounding-dino-base"

print(f"Dang nap mo hinh Grounding DINO: {GROUNDING_DINO_MODEL_ID} ...")
dino_processor = AutoProcessor.from_pretrained(GROUNDING_DINO_MODEL_ID)
dino_model = AutoModelForZeroShotObjectDetection.from_pretrained(GROUNDING_DINO_MODEL_ID).to(device)
dino_model.eval()
print("Grounding DINO da san sang.")

def build_dino_prompt(tag_list):
    """Chuyen danh sach tag tu RAM++ thanh text-prompt dung cu phap Grounding DINO.

    Quy uoc chuan cua Grounding DINO: 1 chuoi duy nhat, chu thuong, cac phrase
    cach nhau boi ". " va KET THUC bang dau cham. Vi du:
    "person. kitchen. apron. counter top."
    (Luu y: ban transformers 4.46.3 dang pin trong notebook nay CHUA ho tro tham so
    tien loi `text_labels` (list-of-list) cua cac ban moi hon -- phai dung chuoi text
    don + tu giai ma label tu input_ids.)
    """
    phrases = [tag.lower().strip() for tag in tag_list if tag.strip()]
    return ". ".join(phrases) + "."


def detect_objects_with_dino(image: Image.Image, tag_list,
                              box_threshold: float = 0.35,
                              text_threshold: float = 0.25):
    """Chay Grounding DINO zero-shot detection voi prompt = cac tag tu RAM++.

    Tra ve list cac dict: {"label": str, "score": float, "box": [x0, y0, x1, y1]}
    (toa do theo pixel, da quy doi ve kich thuoc anh goc).
    """
    # CHỈNH SỬA TẠI ĐÂY: Ép ảnh về định dạng RGB 3 kênh tiêu chuẩn để xóa bỏ kênh RGBA/Alpha lỗi
    image = image.convert("RGB")

    text_prompt = build_dino_prompt(tag_list)

    inputs = dino_processor(images=image, text=text_prompt, return_tensors="pt").to(device)
    with torch.no_grad():
        outputs = dino_model(**inputs)

    results = dino_processor.post_process_grounded_object_detection(
        outputs,
        inputs.input_ids,
        box_threshold=box_threshold,
        text_threshold=text_threshold,
        target_sizes=[image.size[::-1]],  # (height, width)
    )
    result = results[0]  # batch size = 1

    detections = []
    for box, score, label in zip(result["boxes"], result["scores"], result["labels"]):
        detections.append({
            "label": label.strip(),
            "score": round(score.item(), 4),
            "box": [round(coord, 2) for coord in box.tolist()],  # [x0, y0, x1, y1]
        })
    return detections


