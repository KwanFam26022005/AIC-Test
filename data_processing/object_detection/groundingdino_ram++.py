"""## 4. Dong goi metadata -- san sang index vao Elasticsearch

Theo Fig. 2 cua paper, output cua hai nhanh **Tag Detection (RAM)** va **Object Detection
(Grounding DINO)** deu do vao **Database (Elasticsearch)** duoi dang cac field rieng cua moi
keyframe. Ham duoi day mo phong dung schema do.

"""

import json
from datetime import datetime

def build_frame_metadata(frame_id: str, video_id: str, ram_tags, dino_detections):
    """Dong goi ket qua Tag Detection + Object Detection thanh 1 document
    theo schema tuong tu custom index cua Elasticsearch trong paper (muc 5.1).
    """
    return {
        "frame_id": frame_id,
        "video_id": video_id,
        "timestamp_indexed": datetime.utcnow().isoformat(),
        "tags": ram_tags,                       # tu nhanh RAM (Tag Detection)
        "objects": [                              # tu nhanh Grounding DINO (Object Detection)
            {
                "tag": det["label"],
                "confidence": det["score"],
                "bbox_xyxy": det["box"],
            }
            for det in dino_detections
        ],
    }


frame_metadata = build_frame_metadata(
    frame_id="demo_frame_0001",
    video_id="demo_video",
    ram_tags=ram_tags,
    dino_detections=detections,
)

print(json.dumps(frame_metadata, indent=2, ensure_ascii=False))

"""## 5. Pipeline tong hop end-to-end

Gop toan bo cac buoc tren thanh mot ham duy nhat `process_keyframe()`, co the goi lap lai
cho tung keyframe duoc TransNetV2 trich xuat (theo muc 3.1 cua paper), tao thanh quy trinh
batch xu ly cho toan bo tap du lieu ~300h / ~32.5M khung hinh.

"""

def process_keyframe(image_path: str, frame_id: str, video_id: str,
                      box_threshold: float = 0.35, text_threshold: float = 0.25,
                      visualize: bool = True, save_dir: str = "images/annotated"):
    """Pipeline day du cho 1 keyframe: RAM++ -> Grounding DINO -> metadata JSON.

    Mapping voi Fig. 2 cua paper:
      Extract Keyframes -> [Tag Detection (RAM)] -> [Object Detection (Grounding DINO)]
                         -> Database (Elasticsearch)
    """
    # CHỈNH SỬA TẠI ĐÂY: Đảm bảo ép kiểu RGB ngay từ bước mở file từ ổ đĩa
    image = Image.open(image_path).convert("RGB")

    # [1] Tag Detection (RAM)
    tags = get_ram_tags(image)

    # [2] Object Detection (Grounding DINO) -- dung chinh tags vua sinh ra lam prompt
    dets = detect_objects_with_dino(
        image, tags, box_threshold=box_threshold, text_threshold=text_threshold
    )

    # [3] Truc quan hoa (tuy chon, huu ich khi debug / demo)
    if visualize:
        import os
        os.makedirs(save_dir, exist_ok=True)
        save_path = os.path.join(save_dir, f"{frame_id}.jpg")
        draw_detections(image, dets, save_path=save_path)

    # [4] Dong goi metadata san sang dua vao Elasticsearch
    metadata = build_frame_metadata(frame_id, video_id, tags, dets)
    return metadata


# ---- Demo chay pipeline cho 1 keyframe ----
result = process_keyframe(
    image_path="images/demo.jpg",
    frame_id="demo_frame_0001",
    video_id="demo_video",
)
print(json.dumps(result, indent=2, ensure_ascii=False))

# ---- Demo chay pipeline cho NHIEU keyframe (batch), giong thuc te xu ly 1 video ----
import glob

keyframe_paths = sorted(glob.glob("images/*.jpg"))
all_metadata = []

for idx, path in enumerate(keyframe_paths):
    fid = f"frame_{idx:04d}"
    meta = process_keyframe(path, frame_id=fid, video_id="demo_video", visualize=False)
    all_metadata.append(meta)
    print(f"[{idx+1}/{len(keyframe_paths)}] {fid}: {len(meta['tags'])} tags, "
          f"{len(meta['objects'])} bounding boxes")

# Luu toan bo metadata ra file .jsonl, san sang bulk-index vao Elasticsearch
with open("frame_metadata.jsonl", "w", encoding="utf-8") as f:
    for meta in all_metadata:
        f.write(json.dumps(meta, ensure_ascii=False) + "\n")

print(f"\nDa luu metadata cua {len(all_metadata)} keyframe vao frame_metadata.jsonl")

