"""## 3. Truc quan hoa bounding box

Ve ket qua "Bounding boxes of tags" len khung hinh de kiem tra truc quan, tuong tu
hop mau xanh trong Fig. 2 cua paper.

"""

from PIL import ImageDraw, ImageFont
import itertools

PALETTE = ["#FF3B30", "#34C759", "#007AFF", "#FF9500", "#AF52DE", "#00C7BE", "#FFD60A"]

def draw_detections(image: Image.Image, detections, save_path=None):
    """Ve bounding box + label + confidence score len anh, tra ve anh da annotate."""
    annotated = image.convert("RGB").copy()
    draw = ImageDraw.Draw(annotated)
    color_cycle = itertools.cycle(PALETTE)

    try:
        font = ImageFont.truetype("DejaVuSans-Bold.ttf", 16)
    except Exception:
        font = ImageFont.load_default()

    for det, color in zip(detections, color_cycle):
        x0, y0, x1, y1 = det["box"]
        text = f"{det['label']} {det['score']:.2f}"

        draw.rectangle([x0, y0, x1, y1], outline=color, width=3)
        text_bbox = draw.textbbox((x0, y0), text, font=font)
        draw.rectangle(
            [text_bbox[0], text_bbox[1] - 4, text_bbox[2] + 4, text_bbox[3] + 2],
            fill=color,
        )
        draw.text((x0 + 2, y0 - 18), text, fill="white", font=font)

    if save_path:
        annotated.save(save_path)
    return annotated


